function spriteToPixels(art: CoinDef): { x: number; y: number; color: string }[] {
  const pixels: { x: number; y: number; color: string }[] = [];
  for (let y = 0; y < art.rows.length; y++) {
    for (let x = 0; x < art.rows[y].length; x++) {
      const c = art.rows[y][x];
      if (c !== '.') {
        pixels.push({ x, y, color: art.palette[c] ?? '#38bdf8' });
      }
    }
  }
  return pixels;
}

export function CoinSprite({
  symbol,
  size = 40,
  animate = true,
  className,
}: {
  symbol: string;
  size?: number;
  animate?: boolean;
  className?: string;
}) {
  const cleanSymbol = symbol.trim().toUpperCase();
  const art = COIN_ART[cleanSymbol] ?? DEFAULT_COIN;
  const pixels = spriteToPixels(art);
  const cell = size / 16;

  return (
    <div
      aria-hidden
      className={cn('relative shrink-0 select-none', animate && 'animate-wobble', className)}
      style={{
        width: size,
        height: size,
        imageRendering: 'pixelated',
      }}
    >
      {pixels.map((p, i) => (
        <div
          key={i}
          className="absolute transition-colors duration-150"
          style={{
            left: p.x * cell,
            top: p.y * cell,
            width: cell + 0.3,
            height: cell + 0.3,
            backgroundColor: p.color,
            boxShadow: `0 0 ${cell * 0.8}px ${p.color}aa`,
          }}
        />
      ))}
    </div>
  );
}

