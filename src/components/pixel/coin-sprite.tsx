const COLORS: Record<string, string> = {
  '3': 'var(--crt-green)',
  '5': 'var(--crt-cyan)',
  '9': 'var(--crt-yellow)',
  'e': 'var(--crt-dim)',
  'b': 'var(--crt-orange)',
  '2': 'var(--crt-red)',
  'd': 'var(--crt-purple)',
};

function spriteToPixels(art: string[]): { x: number; y: number; color: string }[] {
  const pixels: { x: number; y: number; color: string }[] = [];
  for (let y = 0; y < art.length; y++) {
    for (let x = 0; x < art[y].length; x++) {
      const c = art[y][x];
      if (c !== '.') pixels.push({ x, y, color: COLORS[c] ?? 'var(--crt-green)' });
    }
  }
  return pixels;
}

export function CoinSprite({
  symbol,
  size = 40,
  animate = true,
  className,
}: {
  symbol: string;
  size?: number;
  animate?: boolean;
  className?: string;
}) {
  const art = COIN_ART[symbol.toUpperCase()] ?? COIN_ART.BTC;
  const pixels = spriteToPixels(art);
  const cell = size / 16;

  return (
    <div
      aria-hidden
      className={cn('relative shrink-0', animate && 'animate-wobble', className)}
      style={{
        width: size,
        height: size,
        imageRendering: 'pixelated',
        animationDuration: animate ? undefined : 'none',
      }}
    >
      {pixels.map((p, i) => (
        <div
          key={i}
          className="absolute"
          style={{
            left: p.x * cell,
            top: p.y * cell,
            width: cell + 0.5,
            height: cell + 0.5,
            background: p.color,
          }}
        />
      ))}
    </div>
  );
}

